"""Generate the on-disk JSON Schema bundle from the Pydantic models.

The schemas live as ``.json`` files next to this module so they ship
inside the wheel.  CI calls :func:`generate_all_schemas` and asserts
that the produced bytes match what is committed; that test (in
``agent_foundry/tests/unit/test_foundry_schemas.py``) is what enforces "models and
schemas never drift".

Adding a new schema is a three-step change:

1. Append an entry to :data:`SCHEMA_BUNDLE` mapping a stable file
   name (used by downstream YAML headers) to the Pydantic model.
2. Run ``python -m agent_foundry.schemas._generate`` once and
   commit the resulting ``.json`` file.
3. The CI snapshot test verifies the bundle stays in sync.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, TypeAdapter

from agent_foundry.config import (
    EvaluationConfig,
    WarehouseConfig,
)
from agent_foundry.contracts.agent_app import AgentAppConfig
from agent_foundry.contracts.jobs import JobConfig
from agent_foundry.contracts.mcp import ServerConfig
from agent_foundry.contracts.model_serving import ServingEndpointConfig
from agent_foundry.contracts.skills import (
    SkillDomainMetadata,
    SkillMetadata,
)
from agent_foundry.contracts.tools import ToolManifest
from agent_foundry.contracts.vector_search import IndexConfig
from agent_foundry.public.foundry_config import (
    FoundryInstanceConfig,
    FoundryRepoConfig,
)

# ---------------------------------------------------------------------------
# Bundle definition
# ---------------------------------------------------------------------------

# Mapping of on-disk schema filename -> the contract it projects.
#
# A value is either a Pydantic ``BaseModel`` subclass (rendered via
# ``model_json_schema``) or an annotated discriminated-union type such
# as ``ServerConfig`` (rendered via ``TypeAdapter`` -- see ``_render``).
#
# File names are *part of the contract*: downstream YAML headers
# reference them by exact path (e.g.
# ``# yaml-language-server: $schema=../../../../.agent-foundry/schemas/agent_config.schema.json``).
# Renaming a file here is a breaking change.
SCHEMA_BUNDLE: dict[str, Any] = {
    # Top-level foundry.toml files (the new contract introduced by #191).
    "foundry-repo.schema.json": FoundryRepoConfig,
    "foundry-instance.schema.json": FoundryInstanceConfig,
    # Existing typed brick YAMLs that gain a $schema header in F-PR3.
    "agent_app_config.schema.json": AgentAppConfig,
    # NOTE: the agent payload's ``payload.yml`` schema is payload-owned
    # and generated by ``payloads/agent/schemas`` -- the framework's
    # schema bundle stays agent-agnostic.
    "warehouse_config.schema.json": WarehouseConfig,
    "evaluation_config.schema.json": EvaluationConfig,
    "job_config.schema.json": JobConfig,
    "model_serving_endpoint_config.schema.json": ServingEndpointConfig,
    # skills brick contracts (#323).
    "skill.schema.json": SkillMetadata,
    "skill_domain.schema.json": SkillDomainMetadata,
    "tool_manifest.schema.json": ToolManifest,
    # mcp brick contract (#323). ``ServerConfig`` is a discriminated
    # union, not a BaseModel, so it is rendered via TypeAdapter.
    "mcp_server_config.schema.json": ServerConfig,
    # vector_search brick contract (#322): index_config.yml.
    "vector_search_index_config.schema.json": IndexConfig,
}


# ---------------------------------------------------------------------------
# Generation
# ---------------------------------------------------------------------------


def schemas_dir() -> Path:
    """Absolute path to the directory holding the on-disk schemas.

    Resolved at call time (not at import) so tests can monkeypatch
    ``__file__`` for snapshot comparisons in alternative locations.
    """
    return Path(__file__).resolve().parent


def _render(contract: Any) -> str:
    """Render *contract*'s JSON Schema to a stable, diff-friendly string.

    *contract* is either a Pydantic ``BaseModel`` subclass or an
    annotated discriminated-union type (e.g. ``ServerConfig``). The
    latter is not a ``BaseModel`` so it goes through ``TypeAdapter``,
    which emits a top-level ``oneOf`` over the variant ``$defs`` rather
    than a single ``type: object``. We inject a stable ``title`` so the
    union schema reads sensibly in editors.
    """
    if isinstance(contract, type) and issubclass(contract, BaseModel):
        schema: dict[str, Any] = contract.model_json_schema(mode="validation")
    else:
        schema = TypeAdapter(contract).json_schema(mode="validation")
        # TypeAdapter names the top-level schema ``Annotated`` for an
        # ``Annotated[Union[...], Field(...)]`` contract -- unhelpful in
        # an editor. Override with the stable contract name.
        schema["title"] = "ServerConfig"
    # ``sort_keys=True`` + a trailing newline keeps the on-disk bytes
    # byte-stable across Pydantic patch releases that may reorder
    # internal dicts.  Indent 2 matches the existing repo style for
    # JSON fixtures.
    return json.dumps(schema, sort_keys=True, indent=2) + "\n"


def generate_all_schemas(
    *,
    out_dir: Path | None = None,
) -> dict[str, str]:
    """Render every entry in :data:`SCHEMA_BUNDLE` to JSON.

    When *out_dir* is given, write each schema to ``out_dir/<filename>``
    (creating *out_dir* if needed).  Otherwise just return the rendered
    strings -- useful for the CI drift check that compares against
    committed bytes without writing.
    """
    rendered: dict[str, str] = {}
    for filename, contract in SCHEMA_BUNDLE.items():
        rendered[filename] = _render(contract)
    if out_dir is not None:
        out_dir = out_dir.resolve()
        out_dir.mkdir(parents=True, exist_ok=True)
        for filename, body in rendered.items():
            (out_dir / filename).write_text(body, encoding="utf-8")
    return rendered


# ---------------------------------------------------------------------------
# ``python -m agent_foundry.schemas._generate`` -- regenerate the bundle
# ---------------------------------------------------------------------------


def main() -> int:
    """Regenerate the on-disk schema files in place.

    Run this after any change to a model in :data:`SCHEMA_BUNDLE` and
    commit the resulting ``.json`` diff alongside the model change.
    """
    target = schemas_dir()
    generate_all_schemas(out_dir=target)
    print(f"Regenerated {len(SCHEMA_BUNDLE)} schemas under {target}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
