"""JSON Schema bundle shipped with the agent-foundry wheel.

Issue #191 (typed foundry config contract), F-PR3.

Why ship schemas inside the wheel
---------------------------------

Downstream repos consume the typed config contract by authoring
``foundry.toml`` (repo root + per-instance) plus a handful of typed
brick YAMLs.  We want IDEs (VS Code via ``yaml-language-server``,
PyCharm, etc.) to autocomplete and validate these files without the
downstream maintainer guessing what keys are valid.

The cleanest delivery channel is JSON Schema.  Two design choices:

1. **Generate from the Pydantic models** (single source of truth).
   The models in :mod:`agent_foundry.public.foundry_config`,
   :mod:`agent_foundry.contracts.agent`, and friends are the
   authoritative contract; the JSON Schema files in this directory
   are deterministic projections of those models.  CI runs
   :func:`generate_all_schemas` and fails if the on-disk files
   diverge from the regenerated bytes.
2. **Ship inside the wheel** rather than at a public URL.
   Keeps the downstream fully self-contained (offline-friendly,
   version-pinned via ``uv.lock``).  The ``agent-foundry sync-schemas``
   CLI verb (added in this PR) copies the bundle into the downstream
   repo's ``.agent-foundry/schemas/`` directory; YAML/TOML files
   then reference the local path via ``# yaml-language-server:``
   headers.

The schema bytes are deliberately committed to git -- not generated
at install time -- so a downstream that builds an air-gapped wheel
or inspects the source tarball can see them.
"""

