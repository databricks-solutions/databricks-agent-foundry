_INSTANCE_FOUNDRY_TOML_BLANK = """\
#:schema ../../.agent-foundry/schemas/foundry-instance.schema.json
#
# Per-instance foundry.toml (typed via
# agent_foundry.public.FoundryInstanceConfig).  Generated by
# ``agent-foundry init`` with the blank starter template.
#
# Add bricks under instances/{project_name}/ and re-run deploy.  See
# ``agent-foundry scaffold --list`` for the available brick scaffolds.

name          = "{project_name}"
description   = "Agent generated by agent-foundry init"
schema_prefix = "{schema_prefix}"

# Runtime toggles (chat_history / MCP / A2A / file upload / charts /
# feedback / skills.loading) are NOT authored here -- they live in the
# agent payload's spec (the single config contract):
# instances/{project_name}/payloads/agent/payload.yml -> spec.
# Scaffold the agent payload with ``agent-foundry scaffold app``
# to create that surface.
"""


def render_instance_foundry_toml_blank(ctx: InitContext) -> str:
    """Render the blank-scope per-instance ``foundry.toml``.

    Only the minimum identity fields the typed contract requires
    (``name``, ``schema_prefix``); everything else derives from
    defaults at load time.  ``schema_prefix`` mirrors ``project_name``
    with hyphens swapped for underscores to satisfy the UC identifier
    rule.
    """
    schema_prefix = ctx.project_name.replace("-", "_")
    return _INSTANCE_FOUNDRY_TOML_BLANK.format(
        project_name=ctx.project_name,
        schema_prefix=schema_prefix,
    )


