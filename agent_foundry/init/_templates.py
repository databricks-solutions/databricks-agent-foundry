_FOUNDRY_TOML_HEADER = """\
#:schema .agent-foundry/schemas/foundry-repo.schema.json
#
# Repo-root foundry.toml (typed via agent_foundry.public.FoundryRepoConfig).
# Generated by ``agent-foundry init`` -- safe to hand-edit afterwards.
#
# Hosts may repeat across targets (same workspace serving dev/staging/prod
# with isolation provided by Unity Catalog); catalogs MUST be unique.

schema_version = 2
"""

_TARGET_BLOCK = """
[targets.{name}]
host    = "{host}"
catalog = "{catalog}"
{profile_line}
"""

_FOUNDRY_TOML_INSTANCE_BLOCK = """
[[instances]]
path = "instances/{project_name}"
"""


def render_foundry_toml(ctx: InitContext) -> str:
    """Render the generated repo's ``foundry.toml``.

    Emits one ``[targets.<name>]`` block per configured target
    (dev/staging/prod) in deterministic order followed by a single
    ``[[instances]]`` block pointing at ``instances/<project_name>/``.
    """
    chunks = [_FOUNDRY_TOML_HEADER]
    for name, target in ctx.target_map().items():
        chunks.append(_render_target_block(name, target))
    chunks.append(_FOUNDRY_TOML_INSTANCE_BLOCK.format(project_name=ctx.project_name))
    return "".join(chunks)


def render_foundry_toml_example(ctx: InitContext) -> str:
    """Render ``foundry.toml.example`` (committed sibling of
    ``foundry.toml``).

    Same content as the generated ``foundry.toml`` -- the example is
    the canonical bootstrap copy.  Downstream operators replace it
    with their own values, which is why ``foundry.toml`` itself is
    gitignored but ``foundry.toml.example`` is committed.
    """
    return render_foundry_toml(ctx)


def _render_target_block(name: str, target: TargetSpec) -> str:
    return _TARGET_BLOCK.format(
        name=name,
        host=target.host,
        catalog=target.catalog,
        profile_line=f'profile = "{target.profile}"' if target.profile else "",
    )


