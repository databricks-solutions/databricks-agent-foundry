# Framework extras selected by starter template. Agent-shaped starters need
# runtime + eval; the lean REST-to-MCP proxy needs rest_mcp + dev, plus call
# because its shipped acceptance tests use the databricks-mcp client.
_DEFAULT_FRAMEWORK_EXTRAS = "runtime,eval,dev"
_STARTER_FRAMEWORK_EXTRAS: dict[str, str] = {
    "rest_mcp_proxy": "rest_mcp,call,dev",
}

