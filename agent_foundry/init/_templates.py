"""String templates for the ``agent-foundry init`` renderer.

The templates here are intentionally plain Python strings with
``str.format`` substitution rather than a heavier templating engine.
Each module-level constant is a template; each public function is a
"render this template against an :class:`InitContext`" helper.

Why no Jinja:

* Adding ``jinja2`` to the framework's runtime dependency tree to
  generate a handful of small files at ``init`` time would be the
  wrong cost/benefit trade.
* The templates have at most a couple of conditional blocks (e.g.
  optional ``[targets.staging]``).  Conditional rendering is handled
  in Python by composing format-string fragments -- simpler to read
  than embedded Jinja loops.

Each template fragment is named with the file it produces so the
renderer can cite them in error messages.
"""

from __future__ import annotations

from agent_foundry.init.examples_registry import get_variant
from agent_foundry.init.wizard import InitContext, TargetSpec

