_VCS_SCHEME_PREFIXES = ("ssh://", "https://", "http://")
"""URL schemes a PEP 610 ``direct_url.json.url`` may carry for a
VCS-backed install.  PEP 508 install specs require these to be
prefixed with ``git+`` when used inside ``pyproject.toml``
``dependencies`` (e.g. ``git+ssh://...``); the bare form makes
``uv`` / ``pip`` parse the dependency line as a relative path and
fail to build the project's metadata.

We deliberately only prepend ``git+``: PEP 610 records the VCS in
``vcs_info.vcs``, but the only VCS we test the framework against is
git and supporting hg / bzr / svn would broaden the contract beyond
what the wizard's UX claims.  If a future user installs the
framework from a non-git VCS the helper will silently mis-prefix --
that is acceptable for an opinionated bootstrap tool.
"""


def _ensure_vcs_pip_prefix(url: str) -> str:
    """Coerce a PEP 610 install URL into the PEP 508 pip-spec form.

    ``direct_url.json`` records VCS URLs without the ``git+`` prefix
    (the VCS type lives in ``vcs_info.vcs``).  pip / uv inside
    ``pyproject.toml`` ``dependencies`` lines, on the other hand,
    require ``git+ssh://...`` / ``git+https://...`` -- without the
    prefix the spec parses as a malformed relative path and the
    project build aborts.

    Pass-through when:

    * the URL is empty (caller will fall back to the canonical URL);
    * the URL already has a ``git+`` (or any VCS) prefix;
    * the URL scheme is not in :data:`_VCS_SCHEME_PREFIXES` (the
      caller passed something we do not understand, e.g. ``file://``
      from a local checkout -- leave it alone so the user sees the
      real value and can hand-edit).
    """
    if not url:
        return url
    if url.startswith("git+") or url.startswith(("hg+", "bzr+", "svn+")):
        return url
    for scheme in _VCS_SCHEME_PREFIXES:
        if url.startswith(scheme):
            return f"git+{url}"
    return url


def _framework_extras_for(starter_template: str) -> str:
    """Return the ``agent-foundry[...]`` extras for *starter_template*."""
    return _STARTER_FRAMEWORK_EXTRAS.get(starter_template, _DEFAULT_FRAMEWORK_EXTRAS)


def render_pyproject(ctx: InitContext) -> str:
    """Render the generated repo's ``pyproject.toml``.

    The framework pin uses the SHA discovered at ``init`` time when
    available (``framework_sha``), falling back to whatever ref the
    distribution metadata recorded (``framework_install_url`` may be
    empty for path / sdist installs -- those callers must hand-edit
    the pin afterwards).

    URL form: PEP 610 ``direct_url.json`` records VCS URLs without
    the ``git+`` prefix, but PEP 508 install specs inside
    ``pyproject.toml`` ``dependencies`` require it.  We normalise
    via :func:`_ensure_vcs_pip_prefix` so the generated pin works
    with ``uv sync`` / ``pip install`` out of the box.

    Extras follow the starter payload: agent-shaped starters get
    ``[runtime,eval,dev]``; ``rest_mcp_proxy`` gets ``[rest_mcp,call,dev]``.
    """
    framework_ref = ctx.framework_sha or "main"
    framework_install_url = _ensure_vcs_pip_prefix(
        ctx.framework_install_url or "git+https://github.com/databricks-solutions/databricks-agent-foundry.git",
    )
    return _PYPROJECT_TEMPLATE.format(
        project_name=ctx.project_name,
        framework_extras=_framework_extras_for(ctx.starter_template),
        framework_install_url=framework_install_url,
        framework_ref=framework_ref,
    )


