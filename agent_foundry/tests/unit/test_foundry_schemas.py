"""Drift + content tests for the shipped JSON Schema bundle (#191, F-PR3).

The schemas in ``agent_foundry/schemas/*.schema.json`` are committed
generated artifacts.  This test suite ensures three properties:

1. The on-disk bytes always match a fresh render of the corresponding
   Pydantic model -- so a model change without a schema regenerate
   fails CI loudly.
2. Each schema file is valid JSON.
3. The contract-sensitive bits (``additionalProperties: false``,
   ``schema`` alias, ``$defs`` references) are present where the
   tests in :mod:`tests.test_foundry_config_models` assert they
   should be.  Belt-and-braces: the model tests fail if the rule
   regresses; these tests fail if the JSON projection regresses.
"""

from __future__ import annotations

import json

import pytest

from agent_foundry.schemas import (
    SCHEMA_BUNDLE,
    generate_all_schemas,
    schemas_dir,
)


def test_bundle_lists_expected_filenames() -> None:
    """The set of shipped schemas is part of the contract.  Adding
    or renaming a file is a deliberate change reviewers should see.
    """
    # The agent payload's schema (``agent_payload.schema.json``) is no
    # longer part of the framework bundle -- it is payload-owned and
    # generated by ``payloads/agent/schemas/_generate.py`` so the
    # framework schema bundle stays agent-agnostic (hard cutover, 2.0).
    assert set(SCHEMA_BUNDLE) == {
        "foundry-repo.schema.json",
        "foundry-instance.schema.json",
        "agent_app_config.schema.json",
        "warehouse_config.schema.json",
        "evaluation_config.schema.json",
        "job_config.schema.json",
        "model_serving_endpoint_config.schema.json",
        "skill.schema.json",
        "skill_domain.schema.json",
        "tool_manifest.schema.json",
        "mcp_server_config.schema.json",
        "vector_search_index_config.schema.json",
    }


@pytest.mark.parametrize("filename", sorted(SCHEMA_BUNDLE))
def test_committed_schema_matches_freshly_generated(filename: str) -> None:
    """The committed bytes must match what the generator produces *now*.

    If a Pydantic model changed but the on-disk JSON wasn't regenerated,
    this test fails with a diff hint.  The fix is::

        python -m agent_foundry.schemas._generate
        git add agent_foundry/schemas/

    and commit the result alongside the model change.
    """
    on_disk = (schemas_dir() / filename).read_text(encoding="utf-8")
    rendered = generate_all_schemas()[filename]
    assert on_disk == rendered, (
        f"Schema drift in {filename}.  Run `python -m agent_foundry.schemas._generate` and commit."
    )


# ``mcp_server_config`` projects a discriminated *union* (six server
# types), so its top-level schema is a ``oneOf`` over the variants
# rather than a single ``type: object`` -- the smoke check below
# special-cases it.
_UNION_SCHEMAS = {"mcp_server_config.schema.json"}


@pytest.mark.parametrize("filename", sorted(SCHEMA_BUNDLE))
def test_each_schema_is_valid_json(filename: str) -> None:
    """Reject any file that ships malformed JSON -- the YAML language
    server would error out at load time.
    """
    body = (schemas_dir() / filename).read_text(encoding="utf-8")
    parsed = json.loads(body)
    # Bare smoke checks; full structural checks live in the dedicated
    # tests below.
    assert "title" in parsed
    if filename in _UNION_SCHEMAS:
        # Discriminated union: a ``oneOf`` over per-type ``$defs`` with
        # a ``discriminator`` so editors can narrow on ``type:``.
        assert isinstance(parsed.get("oneOf"), list) and parsed["oneOf"]
        assert "$defs" in parsed
        assert parsed["discriminator"]["propertyName"] == "type"
    else:
        assert parsed.get("type") == "object"


def test_repo_schema_forbids_additional_properties() -> None:
    """``extra="forbid"`` on FoundryRepoConfig must surface as
    ``additionalProperties: false`` in the JSON Schema so the YAML
    LS rejects unknown keys at edit time, not just at load time.
    """
    schema = json.loads((schemas_dir() / "foundry-repo.schema.json").read_text())
    assert schema["additionalProperties"] is False
    assert schema["$defs"]["InstanceRef"]["additionalProperties"] is False
    assert schema["$defs"]["Target"]["additionalProperties"] is False


def test_instance_schema_forbids_additional_properties() -> None:
    schema = json.loads((schemas_dir() / "foundry-instance.schema.json").read_text())
    assert schema["additionalProperties"] is False


def test_repo_schema_exposes_schema_alias() -> None:
    """The on-disk authoring key is ``schema``, not ``schema_``.
    The JSON Schema must expose the alias so IDEs autocomplete the
    right name.
    """
    schema = json.loads((schemas_dir() / "foundry-repo.schema.json").read_text())
    target_props = schema["$defs"]["Target"]["properties"]
    assert "schema" in target_props
    assert "schema_" not in target_props


def test_instance_schema_requires_identity_fields() -> None:
    """``name`` and ``schema_prefix`` have no defaults -- the schema
    must mark them required so the YAML LS flags missing fields.
    """
    schema = json.loads((schemas_dir() / "foundry-instance.schema.json").read_text())
    required = set(schema.get("required", []))
    assert {"name", "schema_prefix"}.issubset(required)
